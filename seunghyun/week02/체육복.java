/**
 *
 * @풀이
 *
 * 이 문제는 그리디(Greedy) 알고리즘으로 해결할 수 있습니다.
 *
 * 먼저 학생별 체육복 상태를 배열에 저장합니다.
 *
 * 체육복 상태
 *  0 : 체육복이 없는 상태
 *  1 : 체육복이 하나 있는 상태
 *  2 : 여벌 체육복까지 가지고 있는 상태
 *
 * 처음에는 모든 학생이 체육복 하나를 가지고 있다고 생각합니다.
 *
 * lost에 포함된 학생은 체육복을 하나 잃었으므로 -1을 합니다.
 *
 * reserve에 포함된 학생은 여벌 체육복을 하나 가지고 있으므로 +1을 합니다.
 *
 * 이때 중요한 예외 상황이 있습니다.
 *
 * lost = [2]
 * reserve = [2]
 *
 * 2번 학생이 체육복을 하나 도난당했지만
 * 여벌 체육복을 하나 가지고 있는 상황입니다.
 *
 * 결과적으로 체육복이 1개 남아 있으므로
 * 다른 학생에게 빌려줄 수 없습니다.
 *
 * 따라서 단순히 lost와 reserve를 따로 처리하면 안 되고,
 * 두 배열에 동시에 존재하는 학생을 먼저 처리해야 합니다.
 *
 *
 * @처리순서
 *
 * 1. lost와 reserve의 교집합을 확인합니다.
 *
 * 2. 두 배열에 모두 존재하는 학생은
 *    도난당한 체육복과 여벌 체육복을 모두 고려했을 때
 *    체육복이 1개 남은 상태입니다.
 *
 *    따라서 이 학생은 lost와 reserve에서 제외합니다.
 *
 * 3. 남은 reserve 학생을 기준으로
 *    바로 앞번호 학생에게 먼저 빌려줄 수 있는지 확인합니다.
 *
 * 4. 앞번호 학생에게 빌려줄 수 없다면
 *    바로 뒷번호 학생에게 빌려줍니다.
 *
 * 5. 체육복을 빌려준 학생은 reserve에서 사용할 수 없게 됩니다.
 *
 * 6. 최종적으로 체육수업에 참여할 수 있는 학생 수를 계산합니다.
 *
 *
 * @그리디 선택
 *
 * 예를 들어
 *
 * n = 5
 * lost = [2, 4]
 * reserve = [3]
 *
 * 3번 학생은 2번 또는 4번 학생에게 체육복을 빌려줄 수 있습니다.
 *
 * 이때 2번 학생에게 먼저 빌려주는 것이 좋습니다.
 *
 * 3번 → 2번
 *
 * 결과적으로 1명만 체육복을 빌릴 수 있으므로
 * 수업에 참여할 수 있는 학생은 4명이 됩니다.
 *
 * 따라서 여벌 체육복을 가진 학생을 순서대로 확인하면서
 * 가능한 경우 앞번호 학생에게 먼저 빌려주는 방식으로 해결할 수 있습니다.
 *
 *
 * @시간복잡도
 * O(N)
 *
 * n의 범위가 최대 30이므로 반복문을 사용해도 충분합니다.
 *
 * 학생 번호를 기준으로 상태 배열을 한 번 순회하면서 처리하므로
 * 전체 시간 복잡도는 O(N)입니다.
 *
 *
 * @공간복잡도
 * O(N)
 *
 * 각 학생의 체육복 상태를 저장하기 위해
 * clothes 배열을 사용하므로 O(N)입니다.
 */
class Solution {

    public int solution(int n, int[] lost, int[] reserve) {

        int[] clothes = new int[n + 1];

        // 모든 학생이 기본적으로 체육복 1개를 가지고 있다고 설정
        for (int i = 1; i <= n; i++) {
            clothes[i] = 1;
        }

        // 체육복을 도난당한 학생
        for (int student : lost) {
            clothes[student]--;
        }

        // 여벌 체육복을 가지고 있는 학생
        for (int student : reserve) {
            clothes[student]++;
        }

        // 체육복을 빌려줄 수 있는 학생 확인
        for (int i = 1; i <= n; i++) {

            // 여벌 체육복이 있는 학생만 확인
            if (clothes[i] != 2) {
                continue;
            }

            // 앞번호 학생에게 빌려주기
            if (i > 1 && clothes[i - 1] == 0) {
                clothes[i - 1]++;
                clothes[i]--;
            }

            // 앞번호에 빌려줄 수 없다면 뒷번호 학생에게 빌려주기
            else if (i < n && clothes[i + 1] == 0) {
                clothes[i + 1]++;
                clothes[i]--;
            }
        }

        // 체육복이 있는 학생 수 계산
        int answer = 0;

        for (int i = 1; i <= n; i++) {
            if (clothes[i] > 0) {
                answer++;
            }
        }

        return answer;
    }
}
