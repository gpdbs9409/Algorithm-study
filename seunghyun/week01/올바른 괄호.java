/**
 * @프로그래머스 12909
 *
 * @문제설명
 * 괄호가 바르게 짝지어졌다는 것은 '(' 문자로 열렸으면 반드시 짝지어서 ')' 문자로 닫혀야 한다는 뜻입니다.
 *
 * 예를 들어
 * "()()" 또는 "(())()" 는 올바른 괄호입니다.
 * ")()(" 또는 "(()(" 는 올바르지 않은 괄호입니다.
 *
 * '(' 또는 ')' 로만 이루어진 문자열 s가 주어졌을 때,
 * 문자열 s가 올바른 괄호이면 true를 return 하고,
 * 올바르지 않은 괄호이면 false를 return 하는 solution 함수를 완성해 주세요.
 *
 * @제한사항
 * 문자열 s의 길이 : 100,000 이하의 자연수
 * 문자열 s는 '(' 또는 ')' 로만 이루어져 있습니다.
 *
 * @풀이
 *
 * 조건1. '('가 나오면 괄호를 하나 연 것으로 판단한다.
 *        ')'가 나오면 앞에서 열린 '(' 하나를 닫는 것으로 판단한다.
 *
 * 조건2. ')'가 나왔을 때 현재까지 열린 '('가 없다면
 *        올바르지 않은 괄호이므로 false를 반환한다.
 *
 * 조건3. 문자열을 모두 확인한 후에도 열린 '('가 남아 있다면
 *        닫히지 않은 괄호가 존재하는 것이므로 false를 반환한다.
 *
 * 조건4. 괄호의 개수가 맞더라도 순서가 잘못되었을 경우에는 false 처리한다.
 *
 * 예를 들어 ")("의 경우
 * '('와 ')'의 개수는 각각 1개로 동일하지만,
 * 첫 번째 문자가 ')'이므로 올바른 괄호가 아니다.
 *
 * 따라서 스택을 이용하여 '('가 나오면 push하고,
 * ')'가 나오면 pop하는 방식으로 처리할 수 있다.
 *
 * 하지만 이 문제에서는 실제로 괄호 문자를 저장할 필요가 없다.
 * 현재 열려 있는 괄호의 개수만 알면 되기 때문에 count 변수 하나만 사용한다.
 *
 * '(' -> count 증가
 * ')' -> count 감소
 *
 * 이때 count가 0보다 작아지는 순간,
 * 닫을 수 있는 '('보다 ')'가 먼저 나온 것이므로 false를 반환한다.
 *
 * 마지막까지 확인했을 때 count가 0이면
 * 모든 '('가 정상적으로 ')'와 짝을 이룬 것이므로 true를 반환한다.
 *
 *
 * @시간복잡도
 * O(N)
 * 문자열을 한 번 순회한다.
 *
 * @공간복잡도
 * O(1)
 * 별도의 자료구조를 사용하지 않고 count 변수 하나만 사용한다.
 */
import java.util.Stack;

class Solution {
    boolean solution(String s) {
        Stack<Character> st = new Stack<>();

        for (int i = 0; i < s.length(); i++) {
            if (s.charAt(i) == '(') {
                st.push(s.charAt(i));
            } else if (s.charAt(i) == ')') {
                if (st.isEmpty()) {
                    return false;
                }
                st.pop();
            }
        }

        return st.isEmpty();
    }
}
